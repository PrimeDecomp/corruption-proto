// The prototype's gamepad data has 51 buttons (from 0x64, where our shared header only names
// the first 12 from 0x34).
static const int kLastGamepadButton = 50;

bool CMain::CheckReset() {
  const BOOL resetPressed = OSGetResetButtonState();
  const CControllerGamepadData& pad = gpController->GetGamepadData(0);
  // The chord is buttons 1, 2 and 7 (B, X and Start in Echoes) with nothing else held.
  bool resetChord = true;
  for (int i = 0; i <= kLastGamepadButton && resetChord; ++i) {
    const bool pressed = pad.GetButton(static_cast< EButton >(i)).GetIsPressed();
    switch (i) {
    case 1:
    case 2:
    case 7:
      if (!pressed) {
        resetChord = false;
      }
      break;
    default:
      if (pressed) {
        resetChord = false;
      }
      break;
    }
  }
  if (resetChord) {
    if (mResetInputDelay >= 0.5f) {
      mSoftResetHoldTime += 1.f / 60.f;
      if (mSoftResetHoldTime > 0.5f) {
        mResetButtonHeld = true;
      }
    }
  } else {
    if (mResetInputDelay < 0.5f) {
      mResetInputDelay += 1.f / 60.f;
    }
    mSoftResetHoldTime = 0.f;
  }
  if (!resetPressed && mResetButtonHeld) {
    mResetRequested = true;
  }
  if (!CMemoryCardSys::mIsCardBusy && (mResetRequested || mManageCard || mGameExitReset)) {

    // Unlike Echoes there is no infinite-loop alarm to cancel and no sound system to quit.
    GXDrawDone();
    GXAbortFrame();
    if (!mGameExitReset) {
      gpGameState->GameOptions() = CGameOptions();
      gpGameState->PreviousGameResults() = CGameState::SPreviousGameResults();
      __PADDisableRecalibration(false);
    } else {
      CGameOptions& options = gpGameState->GameOptions();
      options.SetScreenBrightness(4, CGameOptions::GetSliderPosition(4, 0, 8), false);
      options.SetScreenPositionX(0, CGameOptions::GetSliderPosition(0, -30, 30), false);
      options.SetScreenPositionY(0, CGameOptions::GetSliderPosition(0, -19, 19), false);
      options.SetScreenStretch(0, CGameOptions::GetSliderPosition(0, -10, 10), false);
      __PADDisableRecalibration(true);
    }
    {
      CMemoryStreamOut stream(CSaveRegion::GetSaveBuffer(), CSaveRegion::kSaveBufferSize);
      CBitStreamWriter writer(stream);
      writer.WriteBits(CGraphics::GetProgressiveMode() ? 1 : 0, 1);
      writer.WriteBits(sProgressiveModePrompt ? 1 : 0, 1);
      gpGameState->GameOptions().PutTo(writer);
      gpGameState->PreviousGameResults().PutTo(writer);
      writer.FlushAll();
      if (!(writer.GetOutputStream().GetWrittenBytes() < CSaveRegion::kSaveBufferSize)) {
        RS_VERIFY_FAILURE_IN("Main.cpp", 2242,
                             "outBitStream.Stream().GetWrittenBytes() < kGameOptionsFromResetSize",
                             "false",
                             CBasics::Stringize("Need to enlarge game options stream to %d",
                                                stream.GetWrittenBytes()));
      }
      if (!(writer.GetOutputStream().GetWrittenBytes() < CSaveRegion::kSaveBufferSize)) {
        // The original calls the fatal C++ rs_debugger_printf overload (0x804907F0) here.
        rs_debugger_printf("Reset failed: Tried %d", stream.GetWrittenBytes());
      } else {
        OSReport("Wrote: %d\n", writer.GetOutputStream().GetWrittenBytes());
      }
    }

    gpGameState->GameOptions().EnsureOptions();
    VISetBlack(true);
    VIFlush();
    VIWaitForRetrace();
    if (mManageCard) {
      OSResetSystem(OS_RESET_HOTRESET, 0, true);
    } else if (DVDCheckDisk()) {
      AISetStreamPlayState(0);
      void* savedOptions = CSaveRegion::GetSaveRegionStart();
      memcpy(savedOptions, CSaveRegion::GetSaveBuffer(), CSaveRegion::kSaveBufferSize);
      DCFlushRange(savedOptions, CSaveRegion::kSaveBufferSize);
      OSSetSaveRegion(savedOptions, CSaveRegion::GetSaveRegionEnd());
      OSResetSystem(OS_RESET_RESTART, 0, false);
    } else {
      OSResetSystem(OS_RESET_HOTRESET, 0, false);
    }
    mResetButtonHeld = false;
    mResetRequested = false;
    mGameExitReset = false;
    mManageCard = false;
    return true;
  }
  mResetButtonHeld = resetPressed;
  return false;
}

// The Audio category's tweak load/save options; only the audio tweaks are handled here. Each is
// requested by setting it to 1 and acknowledged by resetting it to 0, and only while the debug
// menu is closed.
void CMain::UpdateTweakDebugOptions() {
  if (!gpGameDebug->IsMenuOpen() &&
      gpGameDebug->GetOption(CGameDebug::kDO_LoadTweaksFromPCHost) != nullptr &&
      gpGameDebug->GetOptionInt(CGameDebug::kDO_LoadTweaksFromPCHost) == 1) {
    gpGameDebug->SetOptionValue(CGameDebug::kDO_LoadTweaksFromPCHost, 0.f);
    gpTweakManager->ReadFromPCHost(rstl::string_l("c:/AudioTweaks.txt"));
  }
  if (!gpGameDebug->IsMenuOpen() &&
      gpGameDebug->GetOption(CGameDebug::kDO_SaveTweaksToPCHost) != nullptr &&
      gpGameDebug->GetOptionInt(CGameDebug::kDO_SaveTweaksToPCHost) == 1) {
    gpGameDebug->SetOptionValue(CGameDebug::kDO_SaveTweaksToPCHost, 0.f);
    gpTweakManager->WriteToPCHost(rstl::string_l("c:/AudioTweaks.txt"));
  }
  if (!gpGameDebug->IsMenuOpen() &&
      gpGameDebug->GetOption(CGameDebug::kDO_LoadTweaksFromMemoryCard) != nullptr &&
      gpGameDebug->GetOptionInt(CGameDebug::kDO_LoadTweaksFromMemoryCard) == 1) {
    gpGameDebug->SetOptionValue(CGameDebug::kDO_LoadTweaksFromMemoryCard, 0.f);
    gpTweakManager->ReadFromMemoryCard(rstl::string_l("AudioTweaks"));
  }
  if (!gpGameDebug->IsMenuOpen() &&
      gpGameDebug->GetOption(CGameDebug::kDO_SaveTweaksToMemoryCard) != nullptr &&
      gpGameDebug->GetOptionInt(CGameDebug::kDO_SaveTweaksToMemoryCard) == 1) {
    gpGameDebug->SetOptionValue(CGameDebug::kDO_SaveTweaksToMemoryCard, 0.f);
    gpTweakManager->WriteToMemoryCard(rstl::string_l("AudioTweaks"));
  }
}

int CMain::RsMain(int argc, const char* const* argv) {
  PPCSetFpIEEEMode();
  CStopwatch startupTimer;
  if (GetLockedCacheAllocationBase() == LCGetBase()) {
    LCEnable();
  }
  RAssert_SetDiagnosticPrintCallback(rs_debugger_printf);
  rstl::single_ptr< CGameGlobalObjects > globalObjects(
      new ("Main.cpp(2351) : ", nullptr) CGameGlobalObjects(*mOsContext, *mMemorySys));
  mGameGlobalObjects = globalObjects.get();
  CStringTable::SetLanguage(GetLanguage());
  for (int i = 0; i < 4; ++i) {
    mTickTimes.AddValue(sInitialTickTime);
    mDrawTimes.AddValue(sInitialDrawTime);
  }
  mAverageTickTime = 0.3f;
  mAverageDrawTime = 0.2f;
  InitializeSubsystems();
  globalObjects->PostInitialize(*mOsContext, *mMemorySys);
  gpGameDebug->AddDebugOptions();
  AddWorldPaks();

  {
    rstl::string audioTweaksStatus;
    bool showAudioTweaksStatus;
    if (gpTweakManager->ReadFromMemoryCard(rstl::string_l("AudioTweaks"))) {
      audioTweaksStatus = rstl::string_l("Loaded audio tweaks from memory card\n");
      showAudioTweaksStatus = true;
    } else {
      audioTweaksStatus = rstl::string_l("FAILED to load audio tweaks from memory card\n");
      showAudioTweaksStatus = true;
    }
    rstl::single_ptr< CGameArchitectureSupport > architecture(
        new ("Main.cpp(2393) : ", nullptr) CGameArchitectureSupport(*mOsContext));
    mArchSupport = architecture.get();
    srand(startupTimer.GetElapsedMicros());
    rs_debugger_printf("Beginning main loop...\n");

    SScreenshotState screenshot;
    if (CSaveRegion::GetNonVolatileSettingsBuffer() != nullptr) {
      CMemoryInStream stream(CSaveRegion::GetNonVolatileSettingsBuffer(),
                             CSaveRegion::kSaveBufferSize);
      CBitStreamReader reader(stream);
      reader.ReadBits(1);
      reader.ReadBits(1);
      gpGameState->GameOptions() = CGameOptions(reader);
      gpGameState->PreviousGameResults() = CGameState::SPreviousGameResults(reader);
      gpGameState->GameOptions().EnsureOptions();
    }

    if (CGraphics::CanSetProgressiveMode()) {
      bool progressive = CGraphics::GetProgressiveDefault();
      // The prototype's gamepad data keeps 51 buttons from 0x64; the Start button is at 0x70.
      if (gpController->GetGamepadData(0).GetButton(kBU_Start).GetIsPressed()) {
        progressive = !progressive;
        gpfnWarningPrintf("Progressive mode has been turned %s\n", progressive ? "ON" : "OFF");
      }
      CGraphics::SetProgressiveMode(progressive);
    }
    if (CDvdFile::FileExists("Strings.pak")) {
      gpfnWarningPrintf("WARNING: Using strings.pak file, strings ingame might be out of date.\n");
    }

    while (!mFinished) {
      gpGameProfiler->Update(1.f / 60.f);
      CProfileSection section(rstl::string_l("Update+Render"));
      architecture->GetStopwatch2().Reset();
      gpResourceFactory->GetResLoader().AsyncIdlePakLoading();
      if (gpMemoryCard == nullptr && gpResourceFactory->GetResLoader().AreAllPaksLoaded()) {
        MemoryCardInitializePump();
        CheckForDuplicateWorlds();
      }
      CARAMManager::CollectGarbage();
      CARAMToken::UpdateAllDMAs();
      if (!architecture->UpdateTicks()) {
        mFinished = true;
      }
      const double tickTime = architecture->GetStopwatch2().GetElapsedTime();
      mTickTimes.AddValue(tickTime / (1.f / 60.f));
      mAverageTickTime = mTickTimes.GetAverage().data();
      architecture->GetStopwatch2().Reset();
      UpdateGPMetrics();

      if (showAudioTweaksStatus) {
        showAudioTweaksStatus = false;
        gpfnWarningPrintf("");
        gpfnWarningPrintf(audioTweaksStatus.data());
        gpfnWarningPrintf(" \n \n ");
        rs_debugger_printf(audioTweaksStatus.data());
      }

      bool drawFrame = true;
      if (IsMaxSpeed()) {
        AsyncIdle(1000000);
        if (mMaxSpeedDrawTimer <= 0.f) {
          mMaxSpeedDrawTimer = 1.f;
        } else {
          drawFrame = false;
          CFrameDelayedKiller::FlushAllocationsForFrame();
          CFrameDelayedKiller::FlushAllocationsForFrame();
        }
      }
      if (drawFrame) {
        gpRender->BeginScene();
        architecture->GetIOWinManager().Draw();
        x70_frameCallbacks.x48_preDraw.Emit();
        DrawDebugMetrics(tickTime, architecture->GetStopwatch2());
        UpdateAudioDebug();
        UpdateScreenCapture(screenshot);
        const double drawTime = architecture->GetStopwatch2().GetElapsedTime();
        mDrawTimes.AddValue(drawTime / (1.f / 60.f));
        mAverageDrawTime = mDrawTimes.GetAverage().data();
        double idleTime =
            (1.f / 60.f - (tickTime + architecture->GetStopwatch2().GetElapsedTime())) - 0.00075;
        // The "+ xtraCPU" streaming status modes hand a whole second to the async loaders.
        if (gpGameDebug->GetOptionInt(CGameDebug::kDO_StreamingStatus) > 2) {
          idleTime = 1.0;
        }
        AsyncIdle(idleTime > 0.0 ? static_cast< uint >(idleTime * 1000000.0) : 0);
        if (gpMain->GetThirtyFps()) {
          const float waitTime =
              1.f / 30.f -
              static_cast< float >(tickTime + architecture->GetStopwatch2().GetElapsedTime());
          if (waitTime > 0.f) {
            CStopwatch::Wait(waitTime);
          }
        }
        section.Stop();
        gpRender->EndScene();
        section.Start();
        if (mGameFrameDrawn) {
          ++architecture->GetFramesDrawn();
          mGameFrameDrawn = false;
        }
      } else {
        gpResourceFactory->AsyncIdle(1000000, false);
      }
      x70_frameCallbacks.x60_postDraw.Emit();
      architecture->Update();
      x70_frameCallbacks.x78_postUpdate.Emit();
      gpGameDebug->GetOption(CGameDebug::kDO_GenericMsgs)->ClearMessages();
      gpGameDebug->GetOption(CGameDebug::kDO_ShowFramerate)->ClearMessages();
      CAudioManager_Update(1.f / 60.f);
      if (CheckTerminate()) {
        gpGameState->AudioGroups().clear();
        break;
      }

      bool resetArchitecture = false;
      if (architecture->GetIOWinManager().IsEmpty()) {
        rs_debugger_printf("IOWinManager got empty.  Resetting game architecture\n");
        resetArchitecture = true;
      } else if (CheckReset()) {
        rs_debugger_printf("Reset pressed...\n");
        resetArchitecture = true;
      }
      if (resetArchitecture) {
        mRestartMode = kRM_Default;
        CStreamAudioManager::StopAll();
        PADRecalibrate(0xf0000000);
        CGraphics::SetIsBeginSceneClearFb(true);
        CGraphics::BeginScene();
        CGraphics::EndScene();
        CFrameDelayedKiller::StallAndFlushAllAllocations();
        architecture = nullptr;
        architecture = new ("Main.cpp(2689) : ", nullptr) CGameArchitectureSupport(*mOsContext);
        mArchSupport = architecture.get();
      }
      UpdateTweakDebugOptions();
    }
  }

  ShutdownSubsystems();
  globalObjects = nullptr;
  CARAMManager::Shutdown();
  rs_debugger_printf("Shutting down the game...\n");
  return 0;
}

void CMain::AsyncIdle(uint time) {
  if (time < 500) {
    uint total = 0;
    for (int i = 0; i < mFrameTimes.capacity(); ++i) {
      total += mFrameTimes[i];
    }
    if (total < 500 * mFrameTimes.capacity()) {
      time = 500;
    } else {
      time = 0;
    }
  }
  mFrameTimes[mFrameTimeIdx] = time;
  mFrameTimeIdx = mFrameTimeIdx + 1;
  if (mFrameTimeIdx >= mFrameTimes.capacity()) {
    mFrameTimeIdx = 0;
  }

  uint idleTime = 5000;
  if (time <= 5000) {
    idleTime = time;
  }
  if (idleTime < mFrameTimeMinimum) {
    idleTime = mFrameTimeMinimum;
  }
  mFrameTimeMinimum = 0;
  bool maxSpeed = false;
  if (IsMaxSpeed()) {
    maxSpeed = true;
    idleTime = 1000000;
  }

  if (idleTime != 0) {
    gpResourceFactory->AsyncIdle(idleTime, maxSpeed);
  }
}

